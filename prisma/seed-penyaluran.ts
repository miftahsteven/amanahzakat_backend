async function main() {
  console.log('🌱 Seeding mustahik, program ZIS, dan penyaluran...');
  for (const m of mustahikSeed) {
    await prisma.mustahik.upsert({
      where: { id: m.id },
      update: { ...m },
      create: { ...m },
    });
  }
  console.log(`✅ ${mustahikSeed.length} mustahik (8 asnaf)`);
  for (const p of programSeed) {
    await prisma.programZis.upsert({
      where: { id: p.id },
      update: { ...p },
      create: { ...p },
    });
  }
  console.log(`✅ ${programSeed.length} program ZIS`);
  for (const rowData of penyaluranSeed) {
    await prisma.transaksiPenyaluran.upsert({
      where: { noPenyaluran: rowData.noPenyaluran },
      update: { ...rowData },
      create: { ...rowData },
    });
  }
  const count = await prisma.transaksiPenyaluran.count();
  const siapBayar = await prisma.transaksiPenyaluran.count({ where: { status: 'Siap Bayar' } });
  const tersalurkan = await prisma.transaksiPenyaluran.count({ where: { status: 'Sudah Tersalurkan' } });
  console.log(`✅ Selesai — ${count} transaksi (${tersalurkan} tersalurkan, ${siapBayar} siap bayar).`);
}
main()
  .catch((e) => {
    console.error('❌ Gagal seed penyaluran:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
