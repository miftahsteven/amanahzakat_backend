type PenyaluranRow = {
  noPenyaluran: string;
  tanggal: string;
  mustahikId: string;
  asnaf: string;
  programId: string;
  nominal: number;
  status: 'Siap Bayar' | 'Sudah Tersalurkan';
  metodePembayaran: string;
  rekeningTujuan: string;
  keterangan: string;
  potonganAmil: number;
  danaMustahik: number;
};
function row(
  noPenyaluran: string,
  tanggal: string,
  mustahikId: string,
  asnaf: string,
  programId: string,
  nominal: number,
  status: 'Siap Bayar' | 'Sudah Tersalurkan',
  metodePembayaran: string,
  rekeningTujuan: string,
  keterangan: string,
): PenyaluranRow {
  const { potonganAmil, danaMustahik } = amil(nominal);
  return {
    noPenyaluran,
    tanggal,
    mustahikId,
    asnaf,
    programId,
    nominal,
    status,
    metodePembayaran,
    rekeningTujuan,
    keterangan,
    potonganAmil,
    danaMustahik,
  };
}
